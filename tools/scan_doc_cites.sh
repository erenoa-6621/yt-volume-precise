#!/usr/bin/env bash
# 文書に書かれた `ファイル名:行番号` の引用が腐っていないかを検査する。
# verify.sh の項目12の本体（回帰テストできるよう切り出してある）。
#
#   usage: tools/scan_doc_cites.sh [--min-anchor-checked N] [対象.md ...]
#          対象を省略すると INSTALL.md を検査する。
#   違反を "対象.md:行番号: 理由" 形式で出力して exit 1。違反が無ければ exit 0。
#   set -e には頼らない。
#
# ─────────────────────────────────────────────────────────────────────────
# なぜ要るか
#   INSTALL.md は「根拠は推測ではなく manifest とコード」と自称している。その自称を
#   検査する機構が無いまま書かれていたので、行番号が外れた引用が4件残った
#   （抜き取りで2件、その後の全数検算でさらに2件）。
#   **文書が自分の正しさを主張するなら、その主張を検査するものが要る。**
#   この製品の主張は一貫して「保証は文章ではなく機構でなければならない」であり、
#   文書だけを例外にしない。
#
# ─────────────────────────────────────────────────────────────────────────
# この検査が保証すること
#   1. 引用先のファイルが実在すること（存在しなければ違反）。
#      表の「場所」欄のような略記（例: content.js）は、リポジトリ内で basename が
#      一意に定まるときだけ解決する。曖昧なら違反、見つからなければ違反。
#   2. 引用された行番号が、引用先のファイルの行数の範囲内であること（範囲外は違反）。
#   3. `file:N-M` の範囲が逆向き（N > M）でないこと、行番号が 1 以上であること。
#   4. **アンカー語が適用できる引用に限り**、その語が引用先の行範囲に実在すること。
#      アンカー語＝引用のすぐ隣に置かれた `バッククォート` の語、または 「…」 の逐語引用。
#
# この検査が保証しないこと（重要。ここを読まずに「緑だから引用は正しい」と言わないこと）
#   * **引用先にその内容が本当に書いてあるかは、機械では判定できない。**
#     行番号が実在の範囲内で内容だけが違う引用（今回の NG-1 がまさにこれ）は、
#     アンカー語が置かれていない限り素通りする。4 の検査は当たれば強いが、網羅ではない。
#   * アンカー語は**字面の一致**しか見ない。文書が `DynamicsCompressorNode` と書き、
#     コードが `createDynamicsCompressor()` と書いていれば、意味は同じでも一致しない。
#     この種の書き分けを赤にすると文書が検査に合わせて歪むので、**適用できる引用だけを
#     検査し、適用できないものは黙って飛ばす**。何件飛ばしたかは必ず出力する。
#   * 引用の「妥当性」（そこを引くのが適切か）は見ない。行番号と字面だけを見る。
#   * 行番号を持たない引用（「README.md の権限方針の節」等）は検査対象外。
#     行番号が動く文書を内容で引くのは正しい書き方だが、この検査は助けにならない。
#
# 空振りしていないことの確かめ方
#   出力の「内容一致まで検査 N 件」が 0 に落ちたら、アンカー規則が対象に当たっていない
#   ということなので、この検査は何も検査していない。verify.sh は
#   --min-anchor-checked で下限を与えて呼ぶ（下回れば赤）。
#   規則が本物の INSTALL.md に効くことは tools/tests/run_scanner_regress.sh が実測する。
# ─────────────────────────────────────────────────────────────────────────

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"

if ! command -v node >/dev/null 2>&1; then
  echo "scan_doc_cites:0: node が無いので検査できない（検査できないものは失敗扱い）"
  exit 1
fi

node "$ROOT/tools/lib/doc_cite_scan.js" --base "$ROOT" "$@"
exit $?
